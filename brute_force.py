import time

# 1. كلمة المرور "السرية" المخفية داخل النظام والتي نريد تخمينها
# (تخيل أنك لا تعرفها وتحاول اختراقها)
target_password = "admin"

# 2. قائمة كلمات المرور المتوقعة (قاموس التخمين - Wordlist)
# المخترق يستخدم قوائم تحتوي على ملايين الكلمات الشهيرة
password_words = ["123456", "password", "qwerty", "master", "admin", "god123"]

print("[-] جاري بدء هجوم التخمين (Brute Force Attack)...")
time.sleep(1) # تأخير بسيط للمحاكاة

found = False

# 3. حلقة تكرارية لتجربة الكلمات واحدة تلو الأخرى
for guess in password_words:
    print(f"[#] تجربة كلمة المرور: {guess}")
    
    # تحقق إذا كانت الكلمة المخمنة تطابق كلمة السر الحقيقية
    if guess == target_password:
        print(f"\n[🎉 SUCCESS]: تم كسر الحماية وتخمين كلمة المرور بنجاح!")
        print(f"🔑 كلمة السر الصحيحة هي: {guess}")
        found = True
        break # إيقاف السكربت فوراً بعد إيجاد الكلمة
    
    time.sleep(0.5) # وقت فاصل بين كل تجربة وتجربة لرؤية العملية

if not found:
    print("\n[-] فشل الهجوم. كلمة المرور ليست موجودة في القائمة الحالية.")